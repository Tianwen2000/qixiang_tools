// 文件说明：提供 wallpaper scenes 前端静态数据或映射配置。
function orb(id, kind, style) {
  return { id, kind, style };
}

function wisp(id, kind, style) {
  return { id, kind, style };
}

function accent(id, kind, style) {
  return { id, kind, style };
}

function particle(id, kind, style) {
  return { id, kind, style };
}

function withMotion(style, customProperties = {}) {
  return {
    ...style,
    ...customProperties,
  };
}

function falling(id, kind, left, top, width, height, duration, delay, travelX, travelY, rotateTo = "16deg") {
  return particle(
    id,
    kind,
    withMotion(
      {
        left,
        top,
        width,
        height,
        animationDuration: duration,
        animationDelay: delay,
      },
      {
        "--travel-x": travelX,
        "--travel-y": travelY,
        "--rotate-to": rotateTo,
      }
    )
  );
}

function dust(id, kind, left, top, size, duration, delay, travelX, travelY) {
  return particle(
    id,
    kind,
    withMotion(
      {
        left,
        top,
        width: size,
        height: size,
        animationDuration: duration,
        animationDelay: delay,
      },
      {
        "--travel-x": travelX,
        "--travel-y": travelY,
      }
    )
  );
}

function glint(id, kind, left, top, size, duration, delay) {
  return particle(id, kind, {
    left,
    top,
    width: size,
    height: size,
    animationDuration: duration,
    animationDelay: delay,
  });
}

function rain(
  id,
  left,
  top,
  height,
  duration,
  delay,
  travelX,
  travelY,
  rotateTo = "11deg",
  width = "2px",
  opacity = "0.62"
) {
  return particle(
    id,
    "rain",
    withMotion(
      {
        left,
        top,
        width,
        height,
        animationDuration: duration,
        animationDelay: delay,
      },
      {
        "--travel-x": travelX,
        "--travel-y": travelY,
        "--rotate-to": rotateTo,
        "--rain-opacity": opacity,
      }
    )
  );
}

function forestFall(prefix, kind, specs) {
  return specs.map(([left, top, width, height, duration, delay, travelX, travelY, rotateTo], index) =>
    falling(`${prefix}-${index + 1}`, kind, left, top, width, height, duration, delay, travelX, travelY, rotateTo)
  );
}

